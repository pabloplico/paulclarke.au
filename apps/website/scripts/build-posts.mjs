#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const APP_ROOT = path.resolve(__dirname, '..');
const POSTS_DIR = path.join(APP_ROOT, 'content', 'posts');
const OUT_FILE = path.join(APP_ROOT, 'server', 'posts.generated.ts');
const ASSETS_DIR = path.join(APP_ROOT, 'dist', 'client');

/** Splits a Markdown file into its front matter (simple `key: value` lines) and body. */
export function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!match) return { data: {}, content: raw };

  const frontmatter = match[1] ?? '';
  const content = match[2] ?? '';
  const data = {};

  for (const line of frontmatter.split('\n')) {
    const colonIdx = line.indexOf(':');
    if (colonIdx === -1) continue;
    const key = line.slice(0, colonIdx).trim();
    let value = line.slice(colonIdx + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    if (value.startsWith('[') && value.endsWith(']')) {
      const inner = value.slice(1, -1);
      data[key] = inner
        .split(',')
        .map((s) => s.trim().replace(/^["']|["']$/g, ''))
        .filter(Boolean);
    } else {
      data[key] = value;
    }
  }

  return { data, content };
}

/** Every `*.md` post in `dir`, its slug taken from the file name. */
export function readPosts(dir = POSTS_DIR) {
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.md')) : [];

  return files.map((filename) => {
    const slug = filename.replace(/\.md$/, '');
    const raw = fs.readFileSync(path.join(dir, filename), 'utf-8');
    const { data, content } = parseFrontmatter(raw);
    return {
      slug,
      title: data.title ?? slug,
      date: data.date ?? '',
      excerpt: data.excerpt ?? '',
      tags: Array.isArray(data.tags) ? data.tags : [],
      content,
    };
  });
}

// Run as a script (not imported by a test): write server/posts.generated.ts
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  // wrangler dev's assets binding requires the directory to exist before startup.
  fs.mkdirSync(ASSETS_DIR, { recursive: true });

  const posts = readPosts();
  const banner = `// AUTO-GENERATED by scripts/build-posts.mjs — do not edit by hand.\n`;
  const body = `export interface GeneratedPost {
  slug: string;
  title: string;
  date: string;
  excerpt: string;
  tags: string[];
  content: string;
}

export const POSTS: GeneratedPost[] = ${JSON.stringify(posts, null, 2)};
`;

  fs.writeFileSync(OUT_FILE, banner + body);
  console.log(`Wrote ${posts.length} post(s) to ${path.relative(APP_ROOT, OUT_FILE)}`);
}
